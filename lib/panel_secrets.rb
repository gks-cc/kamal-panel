require "fileutils"
require "securerandom"
require "yaml"

# Secrets a production panel needs before it can do anything useful: SECRET_KEY_BASE (sessions) and
# the three Active Record encryption keys (SSH keys and tokens are stored encrypted). Environment
# variables always win. When they are not set, the secrets are generated once and kept in
# storage/panel_secrets.yml, inside the panel's volume, so `docker run` with a volume is enough to
# try the panel.
#
# The trade-off: keys kept next to the database protect less than keys kept elsewhere — whoever gets
# a copy of the volume can decrypt the stored SSH keys. The boot log says so; moving the values from
# that file into environment variables (and deleting it) restores the separation.
#
# Keys are only generated on a fresh install (no database yet). A panel that already has data but
# lost its keys must get the original ones back, not new ones that can't read what is stored.
module PanelSecrets
  FILE = "storage/panel_secrets.yml".freeze
  DATABASE = "storage/production.sqlite3".freeze
  ENCRYPTION_KEYS = %w[AR_ENCRYPTION_PRIMARY_KEY AR_ENCRYPTION_DETERMINISTIC_KEY AR_ENCRYPTION_KEY_DERIVATION_SALT].freeze

  module_function

  # Fills ENV with whatever is missing; returns the names it took from (or wrote to) the file.
  def load!(root:, env: ENV, warn: Kernel.method(:warn))
    return [] if env["SECRET_KEY_BASE_DUMMY"] # building the image: nothing may be generated into it

    path = File.join(root, FILE)
    stored = File.exist?(path) ? (YAML.safe_load_file(path) || {}) : {}
    wanted = wanted_keys(env)
    missing = wanted.reject { |name| set?(env[name]) }
    return [] if missing.empty?

    to_generate = missing.reject { |name| set?(stored[name]) }
    if to_generate.any? && File.exist?(File.join(root, DATABASE)) && (to_generate & ENCRYPTION_KEYS).any?
      warn.call("[secrets] #{(to_generate & ENCRYPTION_KEYS).join(', ')} not set and the database already exists: " \
                "not generating new ones, they couldn't read what is stored. Set the original values.")
      to_generate -= ENCRYPTION_KEYS
    end

    if to_generate.any?
      stored = stored.merge(to_generate.to_h { |name| [ name, generate(name) ] })
      write(path, stored)
      warn.call("[secrets] generated #{to_generate.join(', ')} into #{FILE}. They sit in the same volume as the " \
                "database: move them into environment variables and delete the file to keep them apart.")
    end

    (missing & stored.keys).each { |name| env[name] = stored[name] }
  end

  # SECRET_KEY_BASE can also come from the encrypted credentials, when their key is provided.
  def wanted_keys(env)
    set?(env["RAILS_MASTER_KEY"]) ? ENCRYPTION_KEYS : [ "SECRET_KEY_BASE", *ENCRYPTION_KEYS ]
  end

  def generate(name)
    name == "SECRET_KEY_BASE" ? SecureRandom.hex(64) : SecureRandom.alphanumeric(32)
  end

  def write(path, secrets)
    FileUtils.mkdir_p(File.dirname(path))
    tmp = "#{path}.tmp"
    File.open(tmp, File::WRONLY | File::CREAT | File::TRUNC, 0o600) do |file|
      file.write("# Generated by the panel on first boot. Keep it secret; see lib/panel_secrets.rb.\n")
      file.write(secrets.to_yaml)
    end
    File.rename(tmp, path)
  end

  def set?(value) = !value.nil? && !value.to_s.strip.empty?
end
